"""phase2_analysis.py

Purpose: Load the per‑run trace data generated in Phase 1, compute the metrics required for Phase 2, and write both a CSV summary (already produced) and a JSON version for programmatic consumption.

The script can be executed as:

    python scripts/phase2_analysis.py

It assumes the Phase 1 trace files are located under `results/phase1/traces/` and that the summary CSV `results/phase2/research_summary.csv` already exists.
"""
import pathlib, json, pandas as pd, numpy as np, gzip, csv

def bootstrap_ci(series, n_boot=10000, alpha=0.05):
    """Return mean, lower and upper confidence interval using percentile bootstrap."""
    arr = np.asarray(series)
    boot_means = np.random.choice(arr, size=(n_boot, len(arr)), replace=True).mean(axis=1)
    lower = np.percentile(boot_means, 100 * alpha / 2)
    upper = np.percentile(boot_means, 100 * (1 - alpha / 2))
    return arr.mean(), lower, upper

def main():
    # Load summary CSV (generated by Phase 1 aggregation)
    summary_path = pathlib.Path('results/phase2/research_summary.csv')
    df = pd.read_csv(summary_path)

    # Compute bootstrap CI for attack and benign admission rates per warm‑up
    results = []
    for warm in sorted(df['warm_up'].unique()):
        subset = df[df['warm_up'] == warm]
        atk_mean, atk_low, atk_high = bootstrap_ci(subset['attack_admission_rate_mean'])
        ben_mean, ben_low, ben_high = bootstrap_ci(subset['benign_admission_rate_mean'])
        results.append({
            'warm_up': int(warm),
            'attack_admission_rate_mean': atk_mean,
            'attack_admission_rate_ci_low': atk_low,
            'attack_admission_rate_ci_high': atk_high,
            'benign_admission_rate_mean': ben_mean,
            'benign_admission_rate_ci_low': ben_low,
            'benign_admission_rate_ci_high': ben_high,
        })

    json_path = pathlib.Path('results/phase2/research_summary.json')
    json_path.write_text(json.dumps(results, indent=2))
    print(f"Wrote JSON summary to {json_path}")

if __name__ == "__main__":
    main()
